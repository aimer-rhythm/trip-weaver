// 实际上游服务与构建的只读入口检查；只注入一个已完成任务的展示记录。
import { chromium } from 'playwright';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const here = path.dirname(fileURLToPath(import.meta.url));
const origin = 'http://127.0.0.1:18842';
const runId = '570c8f539b074951';
const report = JSON.parse(await readFile(path.join(here, `live/photography/4ad6d27e53d70a5e6e3752e3/runs/${runId}/report.json`), 'utf8'));
const reviewUrl = `/api/photography/review?city=${encodeURIComponent('北京')}&run_id=${runId}`;
const task = { id: 'preview', kind: 'photography', title: '排行景点摄影', group: 'photography', status: 'success', params: { city: '北京' }, duration_seconds: 1, result: { ...report, review_url: reviewUrl } };
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [], writes = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', req => { if (req.method() !== 'GET') writes.push(req.url()); });
  await page.goto(`${origin}/#pipeline`);
  const photoCard = page.locator('[data-slot="card"]').filter({ has: page.locator('#photography-top') });
  await photoCard.waitFor();
  assert.equal(await page.locator('#photography-top').inputValue(), '20');
  assert.equal(await page.locator('#photography-run_id').inputValue(), '');
  assert.ok((await photoCard.textContent()).includes('签名引导'));
  await page.locator('#photography-places').fill('故宫博物院,天坛');
  await page.locator('#photography-mode').click();
  await page.getByRole('option', { name: 'improve', exact: true }).click();
  assert.ok((await page.locator('#photography-mode').textContent()).includes('improve'));
  await photoCard.screenshot({ path: path.join(here, 'verification/upstream-entry.png') });
  const runAllCard = page.locator('[data-slot="card"]').filter({ has: page.locator('#run-all-keywords') });
  const runAllFields = await runAllCard.locator('[id^="run-all-"]').evaluateAll(nodes => nodes.map(node => node.id).sort());
  assert.deepEqual(runAllFields, ['run-all-keywords', 'run-all-with_images']);
  assert.ok((await runAllCard.textContent()).includes('含攻略图文字提取'));
  assert.ok((await runAllCard.textContent()).includes('不保存风景'));
  assert.equal(await page.locator('#run-all-with_images').getAttribute('aria-checked'), 'true');
  await page.locator('#run-all-with_images').click();
  assert.equal(await page.locator('#run-all-with_images').getAttribute('aria-checked'), 'false');
  await page.locator('#run-all-with_images').click();
  await runAllCard.screenshot({ path: path.join(here, 'verification/upstream-run-all.png') });
  await page.route('**/api/tasks/preview', route => route.fulfill({ json: task }));
  await page.route('**/api/tasks/preview/stream', route => route.fulfill({ contentType: 'text/event-stream', body: `data: ${JSON.stringify({ type: 'done', task })}\n\n` }));
  await page.goto(`${origin}/?task=preview#pipeline`);
  const link = page.getByRole('link', { name: '查看摄影精选与候选审核' });
  await link.waitFor();
  assert.equal(await link.getAttribute('href'), reviewUrl);
  const response = await page.request.get(`${origin}${reviewUrl}`);
  assert.equal(response.status(), 200);
  assert.ok(response.headers()['content-security-policy'].includes("default-src 'none'"));
  assert.equal((await page.request.get(`${origin}/api/photography/review?city=北京&run_id=../bad`)).status(), 422);
  const review = await browser.newPage();
  await review.goto(`${origin}${reviewUrl}`);
  const images = await review.locator('img').evaluateAll(async entries => {
    entries.forEach(img => { img.loading = 'eager'; });
    await Promise.all(entries.map(img => img.decode()));
    return entries.length;
  });
  assert.ok(images > 0);
  assert.deepEqual(errors, []);
  assert.deepEqual(writes, []);
  await writeFile(path.join(here, 'verification/upstream-browser.json'), JSON.stringify({ origin, actualConfig: true, taskDisplayFixture: true, runAllFields, images, errors, writes }, null, 2));
  console.log(`上游入口通过：独立TOP20、指定地点、更新模式、全链路仅保留攻略图文字选项、真实审核页 ${images} 张图片，零写请求`);
} finally { await browser.close(); }
